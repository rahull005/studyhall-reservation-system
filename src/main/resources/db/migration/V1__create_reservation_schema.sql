CREATE TABLE resources (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(120) NOT NULL,
                           description VARCHAR(500),
                           active BOOLEAN NOT NULL DEFAULT TRUE,
                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_resources_name_ci
    ON resources (LOWER(name));

CREATE TABLE slots (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       resource_id BIGINT NOT NULL,
                       start_time TIMESTAMPTZ NOT NULL,
                       end_time TIMESTAMPTZ NOT NULL,
                       status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
                       version BIGINT NOT NULL DEFAULT 0,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT fk_slots_resource
                           FOREIGN KEY (resource_id) REFERENCES resources(id),

                       CONSTRAINT chk_slot_time
                           CHECK (end_time > start_time),

                       CONSTRAINT chk_slot_status
                           CHECK (status IN ('AVAILABLE', 'BOOKED')),

                       CONSTRAINT uq_resource_slot_start
                           UNIQUE (resource_id, start_time)
);

CREATE INDEX idx_slots_resource_start
    ON slots (resource_id, start_time);

CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              slot_id BIGINT NOT NULL,
                              customer_name VARCHAR(120) NOT NULL,
                              customer_email VARCHAR(254) NOT NULL,
                              status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
                              idempotency_key VARCHAR(100) NOT NULL,
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              cancelled_at TIMESTAMPTZ,

                              CONSTRAINT fk_reservations_slot
                                  FOREIGN KEY (slot_id) REFERENCES slots(id),

                              CONSTRAINT chk_reservation_status
                                  CHECK (status IN ('CONFIRMED', 'CANCELLED')),

                              CONSTRAINT chk_reservation_cancellation
                                  CHECK (
                                      (status = 'CONFIRMED' AND cancelled_at IS NULL)
                                          OR
                                      (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
                                      ),

                              CONSTRAINT uq_reservation_idempotency
                                  UNIQUE (idempotency_key)
);

CREATE UNIQUE INDEX uq_one_confirmed_reservation_per_slot
    ON reservations (slot_id)
    WHERE status = 'CONFIRMED';

CREATE INDEX idx_reservations_customer_email
    ON reservations (customer_email);
